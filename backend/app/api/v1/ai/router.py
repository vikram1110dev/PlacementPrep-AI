@router.get("/history", response_model=StandardResponse)
def get_chat_history(session_id: str, current_user: User = Depends(get_current_user)):
    history = MemoryManager.get_session_history(session_id)
    messages = [{"role": m.type, "content": m.content} for m in history.messages]
    return StandardResponse(success=True, message="History retrieved", data=messages)
