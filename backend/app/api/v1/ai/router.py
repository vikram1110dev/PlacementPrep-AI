@router.post("/chat")
async def chat_with_mentor(request: ChatRequest, current_user: User = Depends(get_current_user)):
    """
    General chat endpoint utilizing the Multi-Agent LangGraph.
    Streams the response using Server-Sent Events (SSE).
    """
    # 1. Retrieve Memory
    session_id = request.session_id or f"session_{current_user.id}"
    history = MemoryManager.get_session_history(session_id)
    
    # 2. Add current message
    history.add_user_message(request.message)
    
    async def event_stream():
        try:
            # Note: For true token streaming, we'd use astream_events. 
            # For simplicity in this scaffold, we'll stream the graph node updates.
            async for output in mentor_graph.astream({"messages": history.messages}):
                for node_name, state in output.items():
                    if "messages" in state:
                        # Get the latest message generated by the node
                        latest_msg = state["messages"][-1].content
                        yield f"data: {json.dumps({'chunk': latest_msg, 'node': node_name})}\n\n"
                        # Save to memory
                        history.add_ai_message(latest_msg)
                        
            yield "data: [DONE]\n\n"
        except Exception as e:
            yield f"data: {json.dumps({'error': str(e)})}\n\n"

    if request.stream:
        return StreamingResponse(event_stream(), media_type="text/event-stream")
    else:
        # Non-streaming fallback
        result = await mentor_graph.ainvoke({"messages": history.messages})
        final_msg = result["messages"][-1].content
        history.add_ai_message(final_msg)
        return StandardResponse(success=True, message="Success", data={"response": final_msg})

